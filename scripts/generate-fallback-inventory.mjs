#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const check = process.argv.includes('--check');
const roots = ['client/src', 'server', 'extension', 'cf-worker/src', 'ios/Polycast', 'ios/PolycastWidget'];
const ignored = new Set(['node_modules', 'dist', 'build', 'test', 'Tests', 'UITests', 'scripts', 'migrations', 'generated']);
const extensions = new Set(['.js', '.mjs', '.ts', '.tsx', '.swift']);
const alternateCode = /(fallback|offline|retry|repair|unavailable|degraded|unconfigured|cache_miss)/i;

function walk(relativeRoot) {
  const files = [];
  const visit = (relative) => {
    for (const entry of fs.readdirSync(path.join(root, relative), { withFileTypes: true })) {
      if (ignored.has(entry.name) || entry.name.startsWith('.')) continue;
      const child = path.join(relative, entry.name);
      if (entry.isDirectory()) visit(child);
      else if (extensions.has(path.extname(entry.name))) files.push(child);
    }
  };
  visit(relativeRoot);
  return files;
}

const entries = [];
for (const file of roots.flatMap(walk)) {
  if (/\.(?:test|spec)\./.test(file)) continue;
  const source = fs.readFileSync(path.join(root, file), 'utf8');
  for (const match of source.matchAll(/\bcode\s*:\s*['"]([a-zA-Z0-9_.-]+)['"]/g)) {
    const code = match[1];
    if (!alternateCode.test(code)) continue;
    const line = source.slice(0, match.index).split('\n').length;
    const context = source.slice(Math.max(0, match.index - 2_000), Math.min(source.length, match.index + 4_000));
    const adapter = /(reportFallback|emitFallbackDiagnostic|broadcastFallbackNotice|reportSocketFallback|reportSignalDiagnostic|showDiagnostic|showFallbackToast|fallbackDiagnostic|FallbackNoticeCenter\.shared\.show|fallback_notices|pc-page-diagnostic|onFallback)/.test(context)
      || (/makeFallbackDiagnostic/.test(context) && /surfaceBackgroundDiagnostic/.test(context));
    const backgroundResponseAdapter = file === 'extension/background.js' && /result\?\.diagnostic/.test(source) && /surfaceBackgroundDiagnostic/.test(source);
    entries.push({
      code,
      file,
      line,
      structured: adapter || backgroundResponseAdapter || (/\b(source|source:)\b/.test(context) && /\b(operation|operation:)\b/.test(context)),
      logged: adapter || backgroundResponseAdapter || /(logRuntimeDiagnostic|runtimeLog\.|PolycastLog\.|logger\.|req\.log\.|console\.(?:info|warn)\('\[polycast:)/.test(context),
      visible: adapter || backgroundResponseAdapter || /(polycast:fallback|FallbackNoticeCenter|showFallback|fallback_notices|fallbackNotices|setFallbackDiagnosticHeader|broadcastFallback|sendResponse|diagnostic\s*[,}])/.test(context),
    });
  }
}
entries.sort((a, b) => a.code.localeCompare(b.code) || a.file.localeCompare(b.file) || a.line - b.line);

const uniqueCodes = new Set(entries.map((entry) => entry.code));
const incomplete = entries.filter((entry) => !entry.structured || !entry.logged || !entry.visible);
const report = {
  generatedAt: new Date().toISOString(),
  totals: { occurrences: entries.length, uniqueCodes: uniqueCodes.size, incompleteOccurrences: incomplete.length },
  entries,
};
const markdown = `# Fallback and guarded-path inventory

Generated by \`npm run inventory:fallbacks\`. This ledger records every literal alternate-path diagnostic code and proves whether its surrounding implementation is structured, logged, and delivered to a relevant UI. Dynamic codes are covered by the platform diagnostic adapter tests.

| Occurrences | Unique codes | Incomplete |
| ---: | ---: | ---: |
| ${entries.length} | ${uniqueCodes.size} | ${incomplete.length} |

| Code | Location | Structured | Logged | Visible |
| --- | --- | :---: | :---: | :---: |
${entries.map((entry) => `| \`${entry.code}\` | \`${entry.file}:${entry.line}\` | ${entry.structured ? 'yes' : 'NO'} | ${entry.logged ? 'yes' : 'NO'} | ${entry.visible ? 'yes' : 'NO'} |`).join('\n')}
`;
const jsonPath = path.join(root, 'docs/fallback-inventory.json');
const markdownPath = path.join(root, 'docs/FALLBACK_INVENTORY.md');

if (check) {
  const prior = JSON.parse(fs.readFileSync(jsonPath, 'utf8'));
  delete prior.generatedAt;
  const current = structuredClone(report);
  delete current.generatedAt;
  if (JSON.stringify(prior) !== JSON.stringify(current) || fs.readFileSync(markdownPath, 'utf8').replace(/Generated by[^\n]*/, markdown.split('\n')[2]) !== markdown) {
    console.error('Fallback inventory drifted; run npm run inventory:fallbacks');
    process.exit(1);
  }
  if (incomplete.length) {
    console.error(`${incomplete.length} fallback diagnostic occurrences lack structured/logged/visible evidence`);
    process.exit(1);
  }
  console.log(`Fallback inventory current (${uniqueCodes.size} codes, all structured/logged/visible)`);
} else {
  fs.writeFileSync(jsonPath, `${JSON.stringify(report, null, 2)}\n`);
  fs.writeFileSync(markdownPath, markdown);
  console.log(`Generated fallback inventory (${uniqueCodes.size} codes; ${incomplete.length} incomplete occurrences)`);
}
